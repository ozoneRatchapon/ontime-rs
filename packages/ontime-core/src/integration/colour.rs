/// Upstream isColourHex: `#` and 3, 4, 6 or 8 hex digits.
pub fn is_colour_hex(text: &str) -> bool {
    let Some(digits) = text.strip_prefix('#') else {
        return false;
    };
    matches!(digits.len(), 3 | 4 | 6 | 8) && digits.bytes().all(|b| b.is_ascii_hexdigit())
}

pub fn is_css_colour(name: &str) -> bool {
    CSS_COLOUR_NAMES.binary_search(&name).is_ok()
}
